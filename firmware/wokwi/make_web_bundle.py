"""Flatten the firmware into a wokwi.com project (one folder of files to paste in).

Usage: python3 wokwi/make_web_bundle.py   ->  wokwi/web_bundle/
The bundle is generated from the same sources as the PlatformIO build. The
local headers (config.h and lib/kn_core) are inlined into sketch.ino so the web
project needs only five files, and '#define KN_SIMULATION 1' is added on top.
"""
from pathlib import Path
import re
import shutil

FW = Path(__file__).resolve().parents[1]
OUT = FW / "wokwi" / "web_bundle"


def lib_versions() -> list[str]:
    ini = (FW / "platformio.ini").read_text()
    block = ini.split("[common]")[1].split("build_flags")[0]
    libs = re.findall(r"^\s+[\w.-]+/([\w.-]+) @ ([\d.]+)", block, re.M)
    return [f"{name}@{version}" for name, version in libs]


HEADER_DIRS = [FW / "include", FW / "lib" / "kn_core" / "src"]


def inline_local_headers(text: str, seen: set[str]) -> str:
    """Replace #include "x.h" with the file's text (once each), for local headers only."""
    out = []
    for line in text.splitlines():
        m = re.match(r'\s*#include "([\w.]+)"', line)
        path = next((d / m.group(1) for d in HEADER_DIRS if m and (d / m.group(1)).exists()), None)
        if path is None:
            out.append(line)
            continue
        if path.name not in seen:
            seen.add(path.name)
            body = path.read_text().replace("#pragma once\n", "")
            out.append(f"// ---- begin {path.name} ----")
            out.append(inline_local_headers(body, seen))
            out.append(f"// ---- end {path.name} ----")
    return "\n".join(out) + "\n"


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    main_cpp = (FW / "src" / "main.cpp").read_text()
    version = re.search(r'KN_FIRMWARE_VERSION=\\"([^\\]+)\\"', (FW / "platformio.ini").read_text()).group(1)
    header = (
        "// Generated by wokwi/make_web_bundle.py from src/main.cpp. Do not edit here.\n"
        "#define KN_SIMULATION 1\n"
        f'#define KN_FIRMWARE_VERSION "{version}"\n'
    )
    (OUT / "sketch.ino").write_text(header + inline_local_headers(main_cpp, set()))
    for name in ["sht3x.chip.c", "sht3x.chip.json"]:
        shutil.copy(FW / "wokwi" / "chips" / name, OUT / name)
    shutil.copy(FW / "diagram.json", OUT / "diagram.json")
    (OUT / "libraries.txt").write_text("# Wokwi Library List\n" + "\n".join(lib_versions()) + "\n")
    print("wrote", OUT)
    for p in sorted(OUT.iterdir()):
        print("  ", p.name)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Provision one storage node (HW-S2): make its broker user and write the git-ignored firmware/include/secrets.h.

Nothing is edited by hand. The Wi-Fi password is typed at the prompt and is never an argument, so it stays out of chat
and shell history. The broker password is generated, and this script never prints it. Standard library only.

    scripts/provision_node.py --host 192.168.43.10 --device-id kn-node-001 --wifi-ssid MyHotspot
Public broker on the server (P3-2): the node trusts the public roots in firmware/certs/public_broker_roots.pem, the
live chain is checked with the ESP32's TLS library first, and the broker user goes to the server as a password hash
only (the plain password never leaves this machine):
    scripts/provision_node.py --server kisaniti@172.128.33.73 --host mqtt.kisaniti.in --device-id kn-node-001 \
        --wifi-ssid MyHome --force

The certificate check runs before anything for the node is written: on any failure no broker user and no file appear.
A second run makes a new broker password, so it needs --force and the node must be flashed again. Registering the
device on the website stays a separate step: the server, not this file, decides which FPO owns the readings.
"""

from __future__ import annotations

import argparse
import getpass
import os
import re
import secrets
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BROKER = ROOT / "backend" / "ingestion" / "broker"
DEFAULT_OUT = ROOT / "firmware" / "include" / "secrets.h"
PUBLIC_ROOTS = ROOT / "firmware" / "certs" / "public_broker_roots.pem"
PUBLIC_CHECK = ROOT / "deploy" / "check_public_broker_tls.sh"
BROKER_IMAGE = "eclipse-mosquitto:2.0.20"
DEVICE_ID = re.compile(r"[a-z0-9][a-z0-9-]{2,31}")  # the pattern frozen in contracts/devices/v1 and sensor/v1
HOST = re.compile(r"[A-Za-z0-9](?:[A-Za-z0-9.-]{0,251}[A-Za-z0-9])?")
RESERVED_USERS = {"ingestion", "conformance"}  # broker users with rights over every device's topics
MQTT_PORT = 8883


class ProvisionError(Exception):
    """A refusal with a message safe to print: it never holds a password."""


def check_device_id(device_id: str) -> str:
    if not DEVICE_ID.fullmatch(device_id):
        raise ProvisionError(f"device ID {device_id!r} does not match the contract pattern {DEVICE_ID.pattern}")
    if device_id in RESERVED_USERS:
        raise ProvisionError(f"{device_id!r} is a service's broker user, not a device")
    return device_id


def check_host(host: str) -> str:
    if not HOST.fullmatch(host):
        raise ProvisionError(f"host {host!r} is not an IP address or DNS name")
    return host


def check_ssid(ssid: str) -> str:
    size = len(ssid.encode())
    if not 1 <= size <= 32:
        raise ProvisionError(f"a Wi-Fi name must be 1 to 32 bytes; this one is {size}")
    if any(ord(c) < 32 or ord(c) == 127 for c in ssid):
        raise ProvisionError("the Wi-Fi name holds a control character")
    return ssid


def check_wifi_pass(password: str) -> str:
    """WPA2: 8 to 63 printable ASCII characters, or exactly 64 hex digits. The message never repeats the value."""
    printable = all(32 <= ord(c) <= 126 for c in password)
    if (printable and 8 <= len(password) <= 63) or re.fullmatch(r"[0-9A-Fa-f]{64}", password):
        return password
    raise ProvisionError(f"a WPA2 password must be 8 to 63 printable ASCII characters; this one has {len(password)}")


def c_string(value: str) -> str:
    """A C string literal with the same bytes. Three-digit octal, so a following digit cannot join the escape."""
    out: list[str] = []
    for byte in value.encode():
        ch = chr(byte)
        if ch in '\\"?':  # ? guards against trigraphs
            out.append("\\" + ch)
        elif 32 <= byte <= 126:
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def render_secrets_h(
    *, ssid: str, wifi_pass: str, host: str, port: int, device_id: str, mqtt_pass: str, ca_pem: str
) -> str:
    """The same macros as firmware/include/secrets.example.h."""
    lines = pem_bundle_lines(ca_pem)
    ca = " \\\n".join("  " + c_string(line + "\n").replace("\\012", "\\n") for line in lines)
    return (
        "// Generated by scripts/provision_node.py. Git-ignored: never commit it or paste it anywhere.\n"
        "#pragma once\n\n"
        f"#define KN_WIFI_SSID {c_string(ssid)}\n"
        f"#define KN_WIFI_PASS {c_string(wifi_pass)}\n\n"
        f"#define KN_MQTT_HOST {c_string(host)}\n"
        f"#define KN_MQTT_PORT {port}\n"
        f"#define KN_MQTT_USER {c_string(device_id)}\n"
        f"#define KN_MQTT_PASS {c_string(mqtt_pass)}\n\n"
        f"#define KN_DEVICE_ID {c_string(device_id)}\n\n"
        f"#define KN_MQTT_CA_PEM \\\n{ca}\n"
    )


def pem_bundle_lines(ca_pem: str) -> list[str]:
    """One or more PEM certificates (lines starting with # are comments and dropped); anything else is refused.
    The ESP32's TLS library reads every certificate in the string as a trust anchor."""
    lines = [ln.strip() for ln in ca_pem.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
    i, certs = 0, 0
    while i < len(lines):
        if lines[i] != "-----BEGIN CERTIFICATE-----":
            raise ProvisionError("the CA file is not a list of PEM certificates")
        try:
            end = lines.index("-----END CERTIFICATE-----", i + 1)
        except ValueError:
            raise ProvisionError("the CA file is not a list of PEM certificates") from None
        body = lines[i + 1 : end]
        if not body or any(not re.fullmatch(r"[A-Za-z0-9+/=]+", b) for b in body):
            raise ProvisionError("the CA file is not a list of PEM certificates")
        i, certs = end + 1, certs + 1
    if certs == 0:
        raise ProvisionError("the CA file is not a list of PEM certificates")
    return lines


def check_out_path(path: Path) -> Path:
    """A path inside this public repository must be git-ignored; anything else is refused before a password exists."""
    resolved = path.resolve()
    if resolved.is_relative_to(ROOT):
        ignored = subprocess.run(["git", "check-ignore", "-q", str(resolved)], cwd=ROOT, check=False)
        if ignored.returncode != 0:
            raise ProvisionError(f"{resolved} is not git-ignored, and this repository is public")
    return resolved


def write_private(path: Path, text: str) -> None:
    """Owner-only from the first byte; the file appears whole or not at all."""
    tmp = path.with_name(path.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="ascii") as f:
            f.write(text)
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def run_step(what: str, cmd: list[str], cwd: Path = ROOT) -> str:
    """Run a command; a failure reports the step and its output, never the command line, which may hold a password."""
    done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)
    if done.returncode != 0:
        raise ProvisionError(f"{what} failed:\n{done.stdout}{done.stderr}".rstrip())
    return done.stdout


def add_broker_user(device_id: str, password: str) -> None:
    uid = f"{os.getuid()}:{os.getgid()}"
    run_step(
        "adding the broker user",
        [
            *["docker", "run", "--rm", "-u", uid, "-v", f"{BROKER}:/mosquitto/config", BROKER_IMAGE],
            *["mosquitto_passwd", "-b", "/mosquitto/config/passwd", device_id, password],
        ],
    )
    (BROKER / "passwd").chmod(0o644)  # the containers' users read it through a read-only mount (setup_stack.sh)


def password_hash_line(device_id: str, password: str) -> str:
    """The broker's passwd line for this device, made here with mosquitto_passwd; only this line goes to the server."""
    with tempfile.TemporaryDirectory() as d:
        uid = f"{os.getuid()}:{os.getgid()}"
        run_step(
            "hashing the broker password",
            [
                *["docker", "run", "--rm", "-u", uid, "-v", f"{d}:/a", BROKER_IMAGE],
                *["mosquitto_passwd", "-b", "-c", "/a/passwd", device_id, password],
            ],
        )
        line = (Path(d) / "passwd").read_text(encoding="ascii").strip()
    if not line.startswith(device_id + ":$7$") or "\n" in line:
        raise ProvisionError("mosquitto_passwd did not give one password hash line")
    return line


def add_server_broker_user(server: str, ssh_key: Path, line: str) -> None:
    """deploy/broker_user.sh on the server reads the hash line on stdin, so it is in no command line or log."""
    done = subprocess.run(
        ["ssh", "-i", str(ssh_key), "-o", "BatchMode=yes", server, "cd kisaniti && sh broker_user.sh"],
        input=line + "\n",
        capture_output=True,
        text=True,
        check=False,
    )
    if done.returncode != 0:
        raise ProvisionError(f"adding the broker user on the server failed:\n{done.stdout}{done.stderr}".rstrip())
    print(done.stdout.strip())


def reload_broker() -> bool:
    """Make a running broker read the new user. False when none is running: it reads the file when it starts."""
    compose = ["docker", "compose", "--profile", "hardware"]
    running = run_step("looking for the broker", [*compose, "ps", "-q", "--status", "running", "broker"]).strip()
    if not running:
        return False
    run_step("reloading the broker", [*compose, "kill", "-s", "HUP", "broker"])
    return True


def read_wifi_pass(from_stdin: bool) -> str:
    if from_stdin:
        return sys.stdin.readline().rstrip("\r\n")
    if not sys.stdin.isatty():
        raise ProvisionError("the Wi-Fi password is typed at a terminal; run this in a terminal, not through an agent")
    first = getpass.getpass("Wi-Fi password (not shown): ")
    if first != getpass.getpass("Again: "):
        raise ProvisionError("the two passwords differ; nothing was changed")
    return first


def main() -> int:
    ap = argparse.ArgumentParser(description="Make a node's broker user and write its secrets.h.")
    ap.add_argument(
        "--host", required=True, help="address the node uses for the broker, the laptop's IP on the hotspot"
    )
    ap.add_argument("--device-id", required=True, help="for example kn-node-001")
    ap.add_argument("--wifi-ssid", required=True, help="the 2.4 GHz hotspot or router name")
    ap.add_argument("--wifi-pass-stdin", action="store_true", help="read the password from stdin, for scripted checks")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="default: firmware/include/secrets.h")
    ap.add_argument("--force", action="store_true", help="replace an existing file; the node must be flashed again")
    ap.add_argument(
        "--server",
        help="public broker on this SSH target (user@host), e.g. kisaniti@172.128.33.73; --host is then its name",
    )
    ap.add_argument("--ssh-key", type=Path, default=Path.home() / ".ssh" / "kisaniti_azure", help="key for --server")
    a = ap.parse_args()
    try:
        host, device_id, ssid = check_host(a.host), check_device_id(a.device_id), check_ssid(a.wifi_ssid)
        out = check_out_path(a.out)
        if out.exists() and not a.force:
            raise ProvisionError(f"{out} exists. --force makes a new broker password, so that node must be reflashed")
        wifi_pass = check_wifi_pass(read_wifi_pass(a.wifi_pass_stdin))

        if a.server:
            return provision_public(a.server, a.ssh_key, host, device_id, ssid, wifi_pass, out)
        run_step("broker setup", [str(BROKER / "setup_stack.sh"), host])
        verdict = run_step("the certificate check", [str(BROKER / "check_esp32_tls.sh"), host]).strip().splitlines()
        if not verdict or not verdict[-1].startswith("PASS"):
            raise ProvisionError(f"the certificate check did not pass: {verdict[-1] if verdict else 'no output'}")
        print(verdict[-1])

        mqtt_pass = secrets.token_hex(24)
        text = render_secrets_h(
            ssid=ssid,
            wifi_pass=wifi_pass,
            host=host,
            port=MQTT_PORT,
            device_id=device_id,
            mqtt_pass=mqtt_pass,
            ca_pem=(BROKER / "certs" / "ca.crt").read_text(encoding="ascii"),
        )
        add_broker_user(device_id, mqtt_pass)
        write_private(out, text)
        reloaded = reload_broker()
    except ProvisionError as e:
        print(f"FAIL: {e}", file=sys.stderr)
        return 1
    state = "running broker reloaded" if reloaded else "broker reads it when it starts"
    print(f"broker user {device_id}: ready ({state})")
    print(f"written, owner-only: {out}")
    print("next: register the device on the website as DEVICE (real node), then build and flash")
    return 0


def provision_public(
    server: str, ssh_key: Path, host: str, device_id: str, ssid: str, wifi_pass: str, out: Path
) -> int:
    """P3-2: the node talks to the public broker. Same refusals as the local path: the TLS check runs before anything
    for the node is written, and a failure leaves no broker user and no file."""
    if not re.fullmatch(r"[A-Za-z0-9._-]+@[A-Za-z0-9.-]+", server):
        raise ProvisionError(f"--server {server!r} is not user@host")
    roots = PUBLIC_ROOTS.read_text(encoding="ascii")
    pem_bundle_lines(roots)
    verdict = run_step("the certificate check", [str(PUBLIC_CHECK), host, str(MQTT_PORT)]).strip().splitlines()
    if not verdict or not verdict[-1].startswith("PASS"):
        raise ProvisionError(f"the certificate check did not pass: {verdict[-1] if verdict else 'no output'}")
    print(verdict[-1])
    mqtt_pass = secrets.token_hex(24)
    text = render_secrets_h(
        ssid=ssid,
        wifi_pass=wifi_pass,
        host=host,
        port=MQTT_PORT,
        device_id=device_id,
        mqtt_pass=mqtt_pass,
        ca_pem=roots,
    )
    add_server_broker_user(server, ssh_key, password_hash_line(device_id, mqtt_pass))
    write_private(out, text)
    print(f"written, owner-only: {out}")
    print("next: register the device on the public website as DEVICE (real node), then build and flash")
    return 0


if __name__ == "__main__":
    sys.exit(main())
